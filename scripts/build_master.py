#!/usr/bin/env python3
"""Build master/SKILL.md, one self-contained skill file, from the modular files.

Run from the repo root:  python scripts/build_master.py

The modular files stay the source of truth. Edit those, then rebuild.
The master contains SKILL.md, every file in references/, and the source of the
scripts in an appendix, so an agent with only this one file has everything.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MASTER_NAME = "design-playbook"

PARTS = [
    ("process.md", "Process"),
    ("foundations.md", "Foundations"),
    ("interaction-and-a11y.md", "Interaction and accessibility"),
    ("build-and-verify.md", "Build and verify"),
    ("ambition.md", "Ambition"),
    ("figma-and-shadcn.md", "Figma and shadcn"),
    ("motion-review.md", "Motion review"),
    ("capture-workflow.md", "Capture workflow"),
    ("writing.md", "Writing"),
    ("sources-and-conditional.md", "Sources and conditional guidance"),
]
LABEL = {f: f"Part {i + 1}, {title}" for i, (f, title) in enumerate(PARTS)}

SCRIPTS = ["contrast.py", "check_page.py"]


def split_frontmatter(text):
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    return m.group(1), m.group(2)


def relink(text):
    # `references/foo.md` becomes a pointer to the part inside this file.
    def sub(match):
        name = match.group(1)
        return LABEL.get(name, match.group(0))

    text = re.sub(r"`references/([a-z0-9\-]+\.md)`", sub, text)
    # bare `foo.md` mentions inside reference files
    for fname, label in LABEL.items():
        text = text.replace(f"`{fname}`", label)
    return text


def main():
    front, body = split_frontmatter((ROOT / "SKILL.md").read_text(encoding="utf-8"))
    desc = re.search(r"^description: (.*)$", front, re.M).group(1)

    out = [
        "---",
        f"name: {MASTER_NAME}",
        f"description: {desc}",
        "---",
        "",
        "<!-- Generated by scripts/build_master.py. Edit the modular files, then rebuild. -->",
        "",
        "This is the single-file version of the playbook. The parts below hold the same",
        "material as the references/ folder. Part references in the text point to sections",
        "of this file. The scripts are in the appendix: save them to disk to run them.",
        "",
    ]
    out.append(relink(body).strip())

    for fname, title in PARTS:
        text = (ROOT / "references" / fname).read_text(encoding="utf-8").strip()
        # demote the first H1 to an H2 part heading, and push other headings down one level
        lines = text.split("\n")
        shifted = []
        in_code = False
        for i, line in enumerate(lines):
            if line.startswith("```"):
                in_code = not in_code
            if not in_code and line.startswith("#"):
                if i == 0 and line.startswith("# "):
                    shifted.append(f"## {LABEL[fname].split(',')[0]}: {line[2:]}")
                else:
                    shifted.append("#" + line)
            else:
                shifted.append(line)
        out.append("\n---\n")
        out.append(relink("\n".join(shifted)))

    out.append("\n---\n")
    out.append("## Appendix, scripts\n")
    out.append("Save each file to a `scripts/` folder and run it as its header describes.\n")
    for name in SCRIPTS:
        src = (ROOT / "scripts" / name).read_text(encoding="utf-8").rstrip()
        out.append(f"### scripts/{name}\n\n```python\n{src}\n```\n")

    dest = ROOT / "master"
    dest.mkdir(exist_ok=True)
    (dest / "SKILL.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    size = (dest / "SKILL.md").stat().st_size
    print(f"wrote master/SKILL.md ({size:,} bytes)")


if __name__ == "__main__":
    main()
